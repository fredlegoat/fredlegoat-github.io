function checkWordCompletion(word, silent = false, forcedDirection = null) {
    if (!word) return;

    const normalize = (s) => s ? s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toUpperCase() : "";

    let filled = true;
    let hasCorrectLetters = false;

    // Vérifier si le mot est rempli
    word.cells.forEach(([row, col]) => {
        if (!userGrid[row][col]) filled = false;
    });

    if (!filled) return;

    // Valider lettre par lettre (verrouiller les lettres correctes)
    word.cells.forEach(([row, col]) => {
        const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
        if (!cell) return;

        if (normalize(userGrid[row][col]) === normalize(grid[row][col])) {
            // Lettre correcte : la verrouiller
            cell.classList.add('validated');
            cell.classList.remove('highlighted');
            hasCorrectLetters = true;
        } else {
            // Lettre incorrecte : ne pas la verrouiller et enlever toute validation précédente
            cell.classList.remove('validated');
        }
    });

    // Vérifier si TOUT le mot est correct
    let allCorrect = true;
    word.cells.forEach(([row, col]) => {
        if (normalize(userGrid[row][col]) !== normalize(grid[row][col])) allCorrect = false;
    });

    if (allCorrect) {
        // Tout le mot est correct : barrer la définition
        const direction = forcedDirection || currentDirection;
        const defItem = document.querySelector(`[data-word-id="${word.id}"][data-direction="${direction}"]`);
        if (defItem) {
            defItem.style.textDecoration = 'line-through';
            defItem.style.opacity = '0.5';
        }

        // Jouer le son de validation
        if (!silent && settings.sfx) {
            if (!correctAudio) {
                correctAudio = new Audio('mp3/correct.mp3');
                correctAudio.volume = 0.03;
            }
            correctAudio.currentTime = 0;
            correctAudio.play().catch(e => console.log('Correct audio play prevented:', e));
        }

        currentWord = null;

        // Check global victory
        let allWordsCorrect = true;

        // Check all words
        const allWords = [...words.horizontal, ...words.vertical];
        allWords.forEach(w => {
            w.cells.forEach(([r, c]) => {
                if (userGrid[r][c] !== grid[r][c]) allWordsCorrect = false;
            });
        });

        if (allWordsCorrect && !silent) {
            const victory = document.getElementById('victory');
            const victoryTitle = document.getElementById('victory-title');
            const victoryMessage = document.getElementById('victory-message');
            const finalPuzzle = document.getElementById('final-puzzle');
            const nextGridBtn = document.getElementById('next-grid-btn');
            const gameChat = document.getElementById('chat-assistant');
            const floatingNextBtn = document.getElementById('next-grid-floating-btn');

            // Si c'est la dernière grille (grille 6 = index 5)
            if (currentGridIndex === 5) {
                victoryTitle.textContent = 'BRAVO !';
                victoryMessage.textContent = '';

                // Afficher les félicitations (étape 1)
                const finalCongrats = document.getElementById('final-congratulations');
                if (finalCongrats) finalCongrats.style.display = 'block';

                // Cacher le puzzle pour l'instant
                finalPuzzle.style.display = 'none';
                nextGridBtn.style.display = 'none';

                // Cacher le bouton flottant pour la dernière grille
                if (floatingNextBtn) floatingNextBtn.style.display = 'none';

                // Cacher le bouton de réouverture
                const reopenBtn = document.getElementById('reopen-grid6-btn');
                if (reopenBtn) reopenBtn.style.display = 'none';

                // NE PAS couper la musique ni jouer sound_question pour l'instant
                // Cela se fera quand on clique sur "Continuer"

                // Rendre le chat visible et cliquable au-dessus du modal
                if (gameChat) {
                    gameChat.classList.add('above-victory');
                    gameChat.style.opacity = '1';
                    gameChat.style.pointerEvents = 'all';
                }
            } else {
                victoryTitle.textContent = 'NIVEAU TERMINÉ !';
                victoryMessage.textContent = 'Grille complétée avec succès.';
                finalPuzzle.style.display = 'none';
                nextGridBtn.style.display = 'inline-block';

                // Afficher le bouton flottant en bas à droite
                if (floatingNextBtn && currentGridIndex < allGrids.length - 1) {
                    floatingNextBtn.style.display = 'flex';
                    if (typeof gsap !== 'undefined') {
                        gsap.fromTo(floatingNextBtn,
                            { opacity: 0, x: 50 },
                            { opacity: 1, x: 0, duration: 0.5, delay: 0.3, ease: "back.out(1.5)" }
                        );
                    }
                }

                // Retirer la classe si elle existe
                if (gameChat) {
                    gameChat.classList.remove('above-victory');
                }
            }

            victory.classList.add('show');

            if (typeof gsap !== 'undefined') {
                gsap.fromTo(victory.querySelector('.victory-content'),
                    { scale: 0.7, opacity: 0, y: 30 },
                    { scale: 1, opacity: 1, y: 0, duration: 0.4, ease: "back.out(1.7)" }
                );
            }

            if (!completedGrids.includes(currentGridIndex)) {
                completedGrids.push(currentGridIndex);
                unlockNextGrid(currentGridIndex);
            }
        }

    } else {
        // GSAP Shake animation
        word.cells.forEach(([row, col]) => {
            const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
            if (typeof gsap !== 'undefined') {
                gsap.fromTo(cell,
                    { x: -5 },
                    { x: 5, duration: 0.1, repeat: 3, yoyo: true, ease: "power1.inOut", onComplete: () => gsap.set(cell, { x: 0 }) }
                );
            }
        });
    }
}

