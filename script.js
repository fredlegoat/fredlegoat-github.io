// IMPROVED CROSSLIST GENERATOR ALGORITHM with PRIORITY WORDS support
function buildLayout(dictionary, priorityWords = []) {
    const size = 12;
    let grid = Array(size).fill().map(() => Array(size).fill('X'));
    let numbers = Array(size).fill().map(() => Array(size).fill(''));
    let blocked = Array(size).fill().map(() => Array(size).fill(1));
    let placements = [];

    // Deduplicate words by string content to avoid redundant placements
    const seenWords = new Set();
    const uniqueDictionary = [];

    // Process priority words first
    priorityWords.forEach(w => {
        if (!seenWords.has(w.word.toUpperCase())) {
            uniqueDictionary.push({ ...w, word: w.word.toUpperCase(), isPriority: true });
            seenWords.add(w.word.toUpperCase());
        }
    });

    // Process regular dictionary
    dictionary.forEach(w => {
        if (!seenWords.has(w.word.toUpperCase())) {
            uniqueDictionary.push({ ...w, word: w.word.toUpperCase(), isPriority: false });
            seenWords.add(w.word.toUpperCase());
        }
    });

    let wordList = uniqueDictionary.sort((a, b) => {
        if (a.isPriority && !b.isPriority) return -1;
        if (!a.isPriority && b.isPriority) return 1;
        return b.word.length - a.word.length;
    });

    function canPlace(wordStr, r, c, dir) {
        if (dir === 'H') {
            if (c + wordStr.length > size) return false;
            if (c > 0 && grid[r][c - 1] !== 'X') return false;
            if (c + wordStr.length < size && grid[r][c + wordStr.length] !== 'X') return false;

            for (let i = 0; i < wordStr.length; i++) {
                let cell = grid[r][c + i];
                if (cell !== 'X' && cell !== wordStr[i]) return false;
                if (cell === 'X') {
                    if (r > 0 && grid[r - 1][c + i] !== 'X') return false;
                    if (r < size - 1 && grid[r + 1][c + i] !== 'X') return false;
                }
            }
        } else {
            if (r + wordStr.length > size) return false;
            if (r > 0 && grid[r - 1][c] !== 'X') return false;
            if (r + wordStr.length < size && grid[r + wordStr.length][c] !== 'X') return false;

            for (let i = 0; i < wordStr.length; i++) {
                let cell = grid[r + i][c];
                if (cell !== 'X' && cell !== wordStr[i]) return false;
                if (cell === 'X') {
                    if (c > 0 && grid[r + i][c - 1] !== 'X') return false;
                    if (c < size - 1 && grid[r + i][c + 1] !== 'X') return false;
                }
            }
        }
        return true;
    }

    function placeWord(wordObj, r, c, dir, id) {
        let cells = [];
        const wordStr = wordObj.word;
        if (dir === 'H') {
            for (let i = 0; i < wordStr.length; i++) {
                grid[r][c + i] = wordStr[i];
                cells.push([r, c + i]);
            }
        } else {
            for (let i = 0; i < wordStr.length; i++) {
                grid[r + i][c] = wordStr[i];
                cells.push([r + i, c]);
            }
        }
        placements.push({ ...wordObj, r, c, dir, id, cells });
        if (numbers[r][c] === '') numbers[r][c] = id;
    }

    // Count intersections for a potential placement
    function countIntersections(wordStr, r, c, dir) {
        let count = 0;
        if (dir === 'H') {
            for (let i = 0; i < wordStr.length; i++) {
                if (grid[r][c + i] === wordStr[i]) count++;
            }
        } else {
            for (let i = 0; i < wordStr.length; i++) {
                if (grid[r + i][c] === wordStr[i]) count++;
            }
        }
        return count;
    }

    let wordId = 1;
    let placedCount = 0;

    // 1. Place first word in the middle
    let first = wordList.shift();
    if (first) {
        let r = Math.floor(size / 2);
        let c = Math.floor((size - first.word.length) / 2);
        placeWord(first, r, c, 'H', wordId++);
        placedCount++;
    }

    // 2. MULTI-PASS ALGORITHM for maximum word placement - increased passes and limit
    let remainingWords = [...wordList];
    let passCount = 0;
    const maxPasses = 8; // Increased from 3 to 8 for better density

    while (remainingWords.length > 0 && passCount < maxPasses && placedCount < 35) {
        passCount++;
        let wordsPlacedThisPass = 0;
        let unplacedWords = [];

        for (let wordIdx = 0; wordIdx < remainingWords.length; wordIdx++) {
            let candidate = remainingWords[wordIdx];
            let bestPlacement = null;
            let bestScore = 0;

            // Try to attach to EVERY placed word
            for (let pIndex = 0; pIndex < placements.length; pIndex++) {
                let placedWord = placements[pIndex];

                // Try EVERY letter in candidate
                for (let candLetterIdx = 0; candLetterIdx < candidate.word.length; candLetterIdx++) {
                    let candLetter = candidate.word[candLetterIdx];

                    // Try EVERY letter in placed word
                    for (let placedLetterIdx = 0; placedLetterIdx < placedWord.word.length; placedLetterIdx++) {
                        if (placedWord.word[placedLetterIdx] !== candLetter) continue;

                        // Try both directions
                        let positions = [];

                        if (placedWord.dir === 'H') {
                            // Try vertical
                            let intersectR = placedWord.r;
                            let intersectC = placedWord.c + placedLetterIdx;
                            let candR = intersectR - candLetterIdx;
                            let candC = intersectC;

                            if (candR >= 0 && candR + candidate.word.length <= size) {
                                positions.push({ r: candR, c: candC, dir: 'V' });
                            }
                        } else {
                            // Try horizontal
                            let intersectR = placedWord.r + placedLetterIdx;
                            let intersectC = placedWord.c;
                            let candR = intersectR;
                            let candC = intersectC - candLetterIdx;

                            if (candC >= 0 && candC + candidate.word.length <= size) {
                                positions.push({ r: candR, c: candC, dir: 'H' });
                            }
                        }

                        // Evaluate each position
                        for (let pos of positions) {
                            if (canPlace(candidate.word, pos.r, pos.c, pos.dir)) {
                                let score = countIntersections(candidate.word, pos.r, pos.c, pos.dir);
                                // Prefer positions with more intersections
                                if (score > bestScore) {
                                    bestScore = score;
                                    bestPlacement = pos;
                                }
                            }
                        }
                    }
                }
            }

            // Place word if we found a valid position
            if (bestPlacement) {
                placeWord(candidate, bestPlacement.r, bestPlacement.c, bestPlacement.dir, wordId++);
                placedCount++;
                wordsPlacedThisPass++;
            } else {
                unplacedWords.push(candidate);
            }
        }

        remainingWords = unplacedWords;

        // If no words were placed this pass, stop trying
        if (wordsPlacedThisPass === 0) break;
    }

    // Fill the blocked array - mark all cells from placed words as non-blocked
    for (let r = 0; r < size; r++) {
        for (let c = 0; c < size; c++) {
            numbers[r][c] = '';
            blocked[r][c] = 1; // Start with all blocked
        }
    }

    // Mark all cells that are part of placed words as non-blocked
    placements.forEach(placement => {
        placement.cells.forEach(([r, c]) => {
            blocked[r][c] = 0;
        });
    });

    // Group placements and assign IDs
    let newId = 1;
    let horiz = [];
    let vert = [];

    let orderedCells = [];
    placements.forEach(p => {
        let exists = orderedCells.find(oc => oc.r === p.r && oc.c === p.c);
        if (!exists) orderedCells.push({ r: p.r, c: p.c, pList: [p] });
        else exists.pList.push(p);
    });

    orderedCells.sort((a, b) => {
        if (a.r !== b.r) return a.r - b.r;
        return a.c - b.c;
    });

    orderedCells.forEach(oc => {
        numbers[oc.r][oc.c] = newId;
        oc.pList.forEach(p => {
            p.id = newId;
            if (p.dir === 'H') horiz.push({ id: p.id, word: p.word, clue: p.clue, cells: p.cells });
            else vert.push({ id: p.id, word: p.word, clue: p.clue, cells: p.cells });
        });
        newId++;
    });

    console.log(`Grid generated: ${placedCount} words placed (${horiz.length} horizontal, ${vert.length} vertical)`);

    return { grid, numbers, blocked, words: { horizontal: horiz, vertical: vert } };
}

