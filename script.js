function toggleFullscreenManual() {
    const elem = document.documentElement;

    if (!document.fullscreenElement && !document.mozFullScreenElement && !document.webkitFullscreenElement && !document.msFullscreenElement) {
        if (elem.requestFullscreen) {
            elem.requestFullscreen().catch(err => console.log(err));
        } else if (elem.msRequestFullscreen) {
            elem.msRequestFullscreen();
        } else if (elem.mozRequestFullScreen) {
            elem.mozRequestFullScreen();
        } else if (elem.webkitRequestFullscreen) {
            elem.webkitRequestFullscreen(Element.ALLOW_KEYBOARD_INPUT);
        }
    } else {
        if (document.exitFullscreen) {
            document.exitFullscreen();
        } else if (document.msExitFullscreen) {
            document.msExitFullscreen();
        } else if (document.mozCancelFullScreen) {
            document.mozCancelFullScreen();
        } else if (document.webkitExitFullscreen) {
            document.webkitExitFullscreen();
        }
    }
}

// OVERRIDE: Generate a random audio visualizer pattern (SVG) with color support
function generateVisualizerWaveform(color = '#ff6600') {
    const width = 300; // High resolution width
    const height = 28;
    const bars = 70;
    const barWidth = 2;
    const gap = (width - (bars * barWidth)) / (bars - 1);

    let svgContent = `<svg width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" xmlns="http://www.w3.org/2000/svg">`;
    svgContent += `<defs><style>rect{fill:${color};}</style></defs>`;

    for (let i = 0; i < bars; i++) {
        // Random height between 20% and 100% of container height
        // Center biased randomness for more "music-like" look
        const mid = bars / 2;
        const dist = Math.abs(i - mid) / mid; // 0 at center, 1 at edges
        const baseAmp = 1 - (dist * 0.5); // Higher in center

        let h = Math.floor(Math.random() * (height * 0.8 * baseAmp)) + 4;

        // Ensure some variability
        if (Math.random() > 0.8) h = Math.floor(Math.random() * height * 0.9) + 2;

        const y = (height - h) / 2; // Center vertically
        const x = i * (barWidth + gap);

        svgContent += `<rect x="${x}" y="${y}" width="${barWidth}" height="${h}" rx="1"/>`;
    }

    svgContent += `</svg>`;

    // Convert to Data URI
    const svgUrl = `url('data:image/svg+xml;charset=utf-8,${encodeURIComponent(svgContent)}')`;

    // Apply to both BG and FG
    const bg = document.querySelector('.waveform-bg');
    const fg = document.getElementById('waveform-fill');

    // Override CSS filters to ensure pure color
    // Reset filters that might alter the color
    if (bg) {
        bg.style.backgroundImage = svgUrl;
        bg.style.filter = 'opacity(0.3)'; // Simple dimming
    }

    if (fg) {
        fg.style.backgroundImage = svgUrl;
        // Apply glow with matching color
        fg.style.filter = `drop-shadow(0 0 5px ${color}66)`; // Hex with alpha for glow
    }

    // Ensure background size is set correctly
    if (fg && document.getElementById('waveform')) {
        const totalWidth = document.getElementById('waveform').offsetWidth;
        const sizeStyle = `${totalWidth}px 100%`;
        fg.style.backgroundSize = sizeStyle;
        if (bg) bg.style.backgroundSize = sizeStyle;
    }
}

