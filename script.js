// Bonus Smoke Canvas with Golden Color - Same as main smoke
function initBonusSmokeCanvas() {
    const container = document.getElementById('bonus-canvas-container');
    if (!container) return;

    container.style.display = 'block';

    const canvas = document.getElementById('bonusSmokeCanvas');
    if (!canvas) return;

    const ctx = canvas.getContext('2d');

    // Same scale as main smoke
    const scale = 8;
    let width, height;

    function resize() {
        width = canvas.width = Math.ceil(window.innerWidth / scale);
        height = canvas.height = Math.ceil(window.innerHeight / scale);
    }
    resize();
    window.addEventListener('resize', resize);

    // Perlin noise implementation (same as main)
    const permutation = [];
    for (let i = 0; i < 256; i++) {
        permutation[i] = Math.floor(Math.random() * 256);
    }
    const p = [...permutation, ...permutation];

    const fade = (t) => t * t * t * (t * (t * 6 - 15) + 10);
    const lerp = (t, a, b) => a + t * (b - a);
    const grad = (hash, x, y) => {
        const h = hash & 15;
        const u = h < 8 ? x : y;
        const v = h < 4 ? y : h === 12 || h === 14 ? x : 0;
        return ((h & 1) === 0 ? u : -u) + ((h & 2) === 0 ? v : -v);
    };

    const perlin = (x, y) => {
        const X = Math.floor(x) & 255;
        const Y = Math.floor(y) & 255;
        x -= Math.floor(x);
        y -= Math.floor(y);
        const u = fade(x);
        const v = fade(y);
        const a = p[X] + Y;
        const aa = p[a];
        const ab = p[a + 1];
        const b = p[X + 1] + Y;
        const ba = p[b];
        const bb = p[b + 1];

        return lerp(v,
            lerp(u, grad(p[aa], x, y), grad(p[ba], x - 1, y)),
            lerp(u, grad(p[ab], x, y - 1), grad(p[bb], x - 1, y - 1))
        );
    };

    // PERF: 3 noise layers (was 5), 2 octaves (was 3-4), throttled to 15fps
    const fractalNoise = (x, y) => {
        const v1 = perlin(x, y);
        const v2 = perlin(x * 2, y * 2) * 0.5;
        return (v1 + v2) / 1.5;
    };

    let time = 0;

    // Golden color (instead of orange/red)
    const targetR = 185;
    const targetG = 147;
    const targetB = 90;

    function drawSmoke() {
        const imageData = ctx.createImageData(width, height);
        const data = imageData.data;

        for (let y = 0; y < height; y++) {
            for (let x = 0; x < width; x++) {
                const sx = x * scale;
                const sy = y * scale;

                const flow1 = fractalNoise(sx * 0.0008 + time * 0.03, sy * 0.0008 + time * 0.025);
                const flow2 = fractalNoise(sx * 0.001 - time * 0.035, sy * 0.001 + time * 0.028);
                const flow3 = fractalNoise(sx * 0.0012 + time * 0.022, sy * 0.0009 - time * 0.032);

                const combined = flow1 * 0.4 + flow2 * 0.35 + flow3 * 0.25;
                const intensity = Math.max(0, Math.min(1, combined + 0.3));
                const variation = Math.sin(time * 0.015 + sx * 0.01 + sy * 0.008) * 0.35 + 0.75;

                const r = Math.floor(intensity * targetR * variation);
                const g = Math.floor(intensity * targetG * variation);
                const b = Math.floor(intensity * targetB * variation);
                const alpha = Math.floor(intensity * 180);

                const idx = (y * width + x) * 4;
                data[idx] = r;
                data[idx + 1] = g;
                data[idx + 2] = b;
                data[idx + 3] = alpha;
            }
        }

        ctx.putImageData(imageData, 0, 0);
    }

    // PERF: 15fps throttle + pause when hidden
    const TARGET_FPS = 15;
    const FRAME_INTERVAL = 1000 / TARGET_FPS;
    let lastFrameTime = 0;

    function animate(timestamp) {
        requestAnimationFrame(animate);
        if (document.hidden) return;
        if (timestamp - lastFrameTime < FRAME_INTERVAL) return;
        lastFrameTime = timestamp;
        time += 0.32;

        ctx.fillStyle = 'rgba(0, 0, 0, 0.1)';
        ctx.fillRect(0, 0, width, height);

        ctx.globalCompositeOperation = 'lighter';
        drawSmoke();
        ctx.globalCompositeOperation = 'source-over';
    }

    ctx.fillStyle = '#000000';
    ctx.fillRect(0, 0, width, height);

    requestAnimationFrame(animate);
}


