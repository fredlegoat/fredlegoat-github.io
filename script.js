function updateMusicPlayer(gridIndex) {
    const musicData = allGrids[gridIndex].music;
    if (!musicData) return;

    const titleEl = document.getElementById('music-title');
    const artistEl = document.getElementById('music-artist');

    // Reset first
    titleEl.classList.remove('scrolling');
    artistEl.classList.remove('scrolling');
    titleEl.textContent = musicData.title;
    artistEl.textContent = musicData.artist;

    // Check if text overflows and add scrolling animation
    setTimeout(() => {
        const titleParentWidth = titleEl.parentElement.clientWidth;
        const artistParentWidth = artistEl.parentElement.clientWidth;

        if (titleEl.scrollWidth > titleParentWidth) {
            // Duplicate text 3 times with separator for seamless infinite loop
            titleEl.textContent = musicData.title + '   •   ' + musicData.title + '   •   ' + musicData.title;
            titleEl.classList.add('scrolling');
        }

        if (artistEl.scrollWidth > artistParentWidth) {
            // Duplicate text 3 times with separator for seamless infinite loop
            artistEl.textContent = musicData.artist + '   •   ' + musicData.artist + '   •   ' + musicData.artist;
            artistEl.classList.add('scrolling');
        }
    }, 100);

    document.getElementById('music-cover').src = musicData.cover;

    if (!audioPlayer) {
        audioPlayer = document.getElementById('audio-player');
        audioPlayer.addEventListener('timeupdate', updateTime);
        audioPlayer.addEventListener('loadedmetadata', updateTime);
        // Set volume to match slider value (25 squared = 0.0625)
        audioPlayer.volume = 0.0625;

        // Set volume slider to match
        const volumeSlider = document.getElementById('volume-slider');
        if (volumeSlider) volumeSlider.value = 25;
    }

    const wasPlaying = isPlaying;
    const currentSrc = audioPlayer.src;
    const newSrc = musicData.audio;

    // Only change source if it's different to avoid restarting the same track
    if (currentSrc !== newSrc && !currentSrc.endsWith(newSrc)) {
        audioPlayer.src = newSrc;

        if (wasPlaying) {
            audioPlayer.play().catch(e => console.log('Autoplay prevented'));
            isPlaying = true;
            document.getElementById('play-icon').style.display = 'none';
            document.getElementById('pause-icon').style.display = 'block';
        }
    }

    // Generate new random waveform visualizer for this track
    generateVisualizerWaveform(musicData.color || '#ff6600');
    // Update the background smoke color if the function exists
    if (window.updateSmokeColor) window.updateSmokeColor(musicData.color || '#ff6600');
}

