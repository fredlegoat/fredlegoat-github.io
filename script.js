function selectWord(word, direction) {
    currentWord = word;
    currentDirection = direction;

    // Remove all highlights and active states
    document.querySelectorAll('.cell').forEach(c => c.classList.remove('highlighted'));
    document.querySelectorAll('.definition-item').forEach(d => d.classList.remove('active'));

    // Highlight word cells
    word.cells.forEach(([row, col]) => {
        const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
        if (cell) cell.classList.add('highlighted');
    });

    // Mark definition as active
    const defItem = document.querySelector(`[data-word-id="${word.id}"][data-direction="${direction}"]`);
    if (defItem) {
        defItem.classList.add('active');
        // Scroll only the definitions panel, not the whole page
        const definitionsPanel = defItem.closest('.definitions-panel');
        if (definitionsPanel) {
            const itemTop = defItem.offsetTop;
            const panelHeight = definitionsPanel.clientHeight;
            const itemHeight = defItem.clientHeight;
            const scrollTop = itemTop - (panelHeight / 2) + (itemHeight / 2);

            definitionsPanel.scrollTo({
                top: scrollTop,
                behavior: 'smooth'
            });
        }
    }

    // Focus first empty cell or first cell
    const firstEmptyCell = word.cells.find(([row, col]) => !userGrid[row][col]);
    const [row, col] = firstEmptyCell || word.cells[0];
    const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
    if (cell) cell.focus({ preventScroll: true });
}

function handleCellClick(e) {
    const row = parseInt(e.target.dataset.row);
    const col = parseInt(e.target.dataset.col);
    const isValidated = e.target.classList.contains('validated');

    // Effet visuel pour les cellules validées
    if (isValidated && typeof gsap !== 'undefined') {
        gsap.fromTo(e.target,
            { scale: 1 },
            {
                scale: 1.1,
                duration: 0.15,
                yoyo: true,
                repeat: 1,
                ease: "power2.inOut"
            }
        );
    }

    // Find which word(s) this cell belongs to
    const belongsTo = [];

    words.horizontal.forEach(word => {
        if (word.cells.some(([r, c]) => r === row && c === col)) {
            belongsTo.push({ word, direction: 'horizontal' });
        }
    });

    words.vertical.forEach(word => {
        if (word.cells.some(([r, c]) => r === row && c === col)) {
            belongsTo.push({ word, direction: 'vertical' });
        }
    });

    if (belongsTo.length > 0) {
        // Si la cellule est validée, on sélectionne le mot et on focus directement
        if (isValidated) {
            // Si on clique sur le même mot, on toggle vers l'autre direction si possible
            if (currentWord && belongsTo.some(b => b.word.id === currentWord.id && b.direction === currentDirection)) {
                const otherWord = belongsTo.find(b => b.word.id !== currentWord.id || b.direction !== currentDirection);
                if (otherWord) {
                    selectWord(otherWord.word, otherWord.direction);
                    focusFirstNonValidatedCell(otherWord.word);
                } else {
                    // Pas d'autre mot, on reste sur le même
                    focusFirstNonValidatedCell(currentWord);
                }
            } else {
                // Nouveau mot, on le sélectionne
                selectWord(belongsTo[0].word, belongsTo[0].direction);
                focusFirstNonValidatedCell(belongsTo[0].word);
            }
        } else {
            // Cellule non-validée, comportement normal
            if (currentWord && belongsTo.some(b => b.word.id === currentWord.id)) {
                const otherWord = belongsTo.find(b => b.word.id !== currentWord.id || b.direction !== currentDirection);
                if (otherWord) {
                    selectWord(otherWord.word, otherWord.direction);
                }
            } else {
                selectWord(belongsTo[0].word, belongsTo[0].direction);
            }
        }
    }
}

// Nouvelle fonction pour focus sur la première cellule non-validée d'un mot
function focusFirstNonValidatedCell(word) {
    if (!word) return;

    for (let i = 0; i < word.cells.length; i++) {
        const [r, c] = word.cells[i];
        const cell = document.querySelector(`[data-row="${r}"][data-col="${c}"]`);
        if (cell && !cell.classList.contains('validated')) {
            cell.focus();
            return;
        }
    }
}

function handleInput(e) {
    // Bloquer l'input sur les cellules validées
    if (e.target.classList.contains('validated')) {
        // Restaurer la valeur correcte
        const row = parseInt(e.target.dataset.row);
        const col = parseInt(e.target.dataset.col);
        e.target.value = grid[row][col];
        return;
    }

    const row = parseInt(e.target.dataset.row);
    const col = parseInt(e.target.dataset.col);

    // If input is empty (backspace handled by keydown typically, but just in case)
    if (e.target.value === '') {
        userGrid[row][col] = '';
        return;
    }

    // Take the last character typed if multiple (e.g. mobile or overwrite)
    const val = e.target.value;
    const char = val.charAt(val.length - 1).toUpperCase();

    // Overwrite content
    e.target.value = char;
    userGrid[row][col] = char;
    e.target.classList.remove('highlighted-error');

    // Auto-focus to next cell in current word
    if (char && currentWord) {
        const currentIndex = currentWord.cells.findIndex(([r, c]) => r === row && c === col);
        if (currentIndex !== -1 && currentIndex < currentWord.cells.length - 1) {
            const [nextRow, nextCol] = currentWord.cells[currentIndex + 1];
            const nextCell = document.querySelector(`[data-row="${nextRow}"][data-col="${nextCol}"]`);
            // Sauter les cellules validées
            if (nextCell && !nextCell.disabled && !nextCell.classList.contains('validated')) {
                nextCell.focus({ preventScroll: true });
            } else if (nextCell && nextCell.classList.contains('validated')) {
                // Si la prochaine cellule est validée, chercher la suivante non-validée
                for (let i = currentIndex + 1; i < currentWord.cells.length; i++) {
                    const [r, c] = currentWord.cells[i];
                    const cell = document.querySelector(`[data-row="${r}"][data-col="${c}"]`);
                    if (cell && !cell.disabled && !cell.classList.contains('validated')) {
                        cell.focus({ preventScroll: true });
                        break;
                    }
                }
            }
        }
    }
}

function handleFocus(e) {
    // Empêcher le focus sur les cellules validées
    if (e.target.classList.contains('validated')) {
        // Delay blur to allow click event to process
        setTimeout(() => {
            if (e.target.classList.contains('validated')) {
                e.target.blur();
            }
        }, 1);
        return;
    }
    currentCell = e.target;
}

function preventValidatedEdit(e) {
    if (e.target.classList.contains('validated')) {
        if (e.key === 'Backspace' || e.key === 'Delete' || (e.key.length === 1 && e.key.match(/[a-z]/i))) {
            e.preventDefault();
            return false;
        }
    }
}

function handleKeyDown(e) {
    // Check if Enter key is pressed
    if (e.key === 'Enter') {
        e.preventDefault();
        if (currentWord) {
            checkWordCompletion(currentWord);
        } else {
            showToast('⚠️ Sélectionne d\'abord un mot');
        }
    }

    // Backspace Handling: Skip validated cells and clear previous non-validated cell
    if (e.key === 'Backspace') {
        e.preventDefault();

        const cell = e.target;
        const row = parseInt(cell.dataset.row);
        const col = parseInt(cell.dataset.col);

        // If current cell is validated, skip to previous non-validated cell
        if (cell.classList.contains('validated')) {
            moveToPreviousNonValidatedCell(row, col);
            return;
        }

        // If cell has content, clear it and STAY on the same cell
        if (cell.value !== '') {
            cell.value = '';
            userGrid[row][col] = '';
            cell.classList.remove('highlighted-error');
            // Le focus reste sur la cellule actuelle pour pouvoir taper directement
        } else {
            // If already empty, move back to previous non-validated cell and clear it
            moveToPreviousNonValidatedCell(row, col, true);
        }
    }
}

function moveToPreviousCell(row, col) {
    if (!currentWord) return;

    // Find current index in word
    const currentIndex = currentWord.cells.findIndex(([r, c]) => r === row && c === col);

    // If found and not at start
    if (currentIndex > 0) {
        const [prevRow, prevCol] = currentWord.cells[currentIndex - 1];
        const prevCell = document.querySelector(`[data-row="${prevRow}"][data-col="${prevCol}"]`);

        if (prevCell && !prevCell.disabled && !prevCell.classList.contains('validated')) {
            prevCell.focus({ preventScroll: true });
        }
    }
}

function moveToPreviousNonValidatedCell(row, col, clearCell = false) {
    if (!currentWord) return;

    // Find current index in word
    const currentIndex = currentWord.cells.findIndex(([r, c]) => r === row && c === col);

    // Search backwards for the first non-validated cell
    for (let i = currentIndex - 1; i >= 0; i--) {
        const [prevRow, prevCol] = currentWord.cells[i];
        const prevCell = document.querySelector(`[data-row="${prevRow}"][data-col="${prevCol}"]`);

        if (prevCell && !prevCell.disabled && !prevCell.classList.contains('validated')) {
            if (clearCell) {
                // Clear the cell
                prevCell.value = '';
                userGrid[prevRow][prevCol] = '';
                prevCell.classList.remove('highlighted-error');
            }
            prevCell.focus({ preventScroll: true });
            return;
        }
    }
}

// Clear entire current word
function clearCurrentWord() {
    if (!currentWord) return;

    currentWord.cells.forEach(([row, col]) => {
        const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
        if (cell && !cell.classList.contains('validated')) {
            cell.value = '';
            userGrid[row][col] = '';
        }
    });

    // Focus first cell
    const [firstRow, firstCol] = currentWord.cells[0];
    const firstCell = document.querySelector(`[data-row="${firstRow}"][data-col="${firstCol}"]`);
    if (firstCell) firstCell.focus({ preventScroll: true });

    showToast('Mot effacé');
}

