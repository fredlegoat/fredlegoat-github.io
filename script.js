// Track mouse movement on waveform for indicator AND drag logic
function initWaveformIndicator() {
    const waveform = document.getElementById('waveform');
    const indicator = document.getElementById('waveform-indicator');
    const fill = document.getElementById('waveform-fill');

    if (!waveform || !indicator) return;

    let isDragging = false;
    let isHovering = false;
    window.waveformInteracting = false;

    const updateVisualsFromMouse = (e) => {
        const rect = waveform.getBoundingClientRect();
        const x = Math.max(0, Math.min(e.clientX - rect.left, rect.width));
        const percentage = x / rect.width;

        indicator.style.left = (percentage * 100) + '%';
        if (fill) fill.style.width = (percentage * 100) + '%';

        if (audioPlayer && audioPlayer.duration) {
            audioPlayer.currentTime = percentage * audioPlayer.duration;
        }
    };

    waveform.addEventListener('mousedown', (e) => {
        if (e.button !== 0) return; // Only left click
        isDragging = true;
        window.waveformInteracting = true;
        waveform.classList.add('seeking');

        updateVisualsFromMouse(e);
        e.preventDefault();
    });

    document.addEventListener('mouseup', (e) => {
        if (isDragging) {
            isDragging = false;
            waveform.classList.remove('seeking');

            // Allow updateTime to resume control after release
            setTimeout(() => { window.waveformInteracting = false; }, 50);
        }
    });

    // Listen to mousemove on document for smooth dragging even outside waveform
    document.addEventListener('mousemove', (e) => {
        if (isDragging) {
            updateVisualsFromMouse(e);
        } else if (isHovering) {
            const rect = waveform.getBoundingClientRect();
            const x = Math.max(0, Math.min(e.clientX - rect.left, rect.width));
            indicator.style.left = ((x / rect.width) * 100) + '%';
        }
    });

    waveform.addEventListener('mouseleave', () => {
        isHovering = false;
        if (!isDragging) {
            indicator.style.opacity = '0';
        }
    });

    waveform.addEventListener('mouseenter', () => {
        isHovering = true;
        indicator.style.opacity = '1';
    });

    // Store hover state globally so updateTime can check it
    window.waveformHovering = () => isHovering || isDragging;
}

