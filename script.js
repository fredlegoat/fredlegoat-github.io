function showHint() {
    if (!currentWord) {
        showToast('Sélectionne un mot pour un indice');
        return;
    }

    // Find all empty or incorrect cells
    const incorrectCells = [];
    for (const [row, col] of currentWord.cells) {
        if (userGrid[row][col] !== grid[row][col]) {
            incorrectCells.push([row, col]);
        }
    }

    if (incorrectCells.length === 0) {
        showToast('Ce mot est déjà complet!');
        return;
    }

    // Pick a random cell from incorrect cells
    const randomIndex = Math.floor(Math.random() * incorrectCells.length);
    const [row, col] = incorrectCells[randomIndex];

    const cell = document.querySelector(`[data-row="${row}"][data-col="${col}"]`);
    const value = grid[row][col];
    cell.value = value;
    userGrid[row][col] = value;

    // Highlight just this cell briefly
    cell.style.backgroundColor = '#ffff00';
    setTimeout(() => {
        cell.style.backgroundColor = '';
    }, 500);

    hintsUsed++;
    showToast(`Indice: ${value}`);
}

