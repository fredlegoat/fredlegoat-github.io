function openImageLightbox(imageSrc, caption) {
    const lightbox = document.getElementById('image-lightbox');
    const lightboxImage = document.getElementById('lightbox-image');
    const lightboxCaption = document.getElementById('lightbox-caption');
    const lightboxContent = document.getElementById('lightbox-content');

    if (!lightbox || !lightboxImage || !lightboxCaption || !lightboxContent) return;

    // Set image and caption
    lightboxImage.src = imageSrc;
    lightboxCaption.textContent = caption || '';

    // No filter applied
    lightboxImage.style.filter = 'none';

    // Show lightbox
    lightbox.style.display = 'flex';

    // Force reflow for smooth animation
    lightbox.offsetHeight;

    // Animate with GSAP - optimized for 60fps
    if (typeof gsap !== 'undefined') {
        gsap.to(lightbox, {
            opacity: 1,
            duration: 0.25,
            ease: "power1.out",
            force3D: true
        });

        gsap.to(lightboxContent, {
            scale: 1,
            opacity: 1,
            duration: 0.35,
            delay: 0.05,
            ease: "back.out(1.4)",
            force3D: true
        });
    } else {
        lightbox.style.opacity = '1';
        lightboxContent.style.transform = 'scale(1)';
        lightboxContent.style.opacity = '1';
    }

    // Prevent body scroll
    document.body.style.overflow = 'hidden';
}

function closeImageLightbox() {
    const lightbox = document.getElementById('image-lightbox');
    const lightboxContent = document.getElementById('lightbox-content');

    if (!lightbox || !lightboxContent) return;

    // Animate out with GSAP - optimized
    if (typeof gsap !== 'undefined') {
        gsap.to(lightboxContent, {
            scale: 0.9,
            opacity: 0,
            duration: 0.2,
            ease: "power1.in",
            force3D: true
        });

        gsap.to(lightbox, {
            opacity: 0,
            duration: 0.2,
            delay: 0.05,
            ease: "power1.in",
            force3D: true,
            onComplete: () => {
                lightbox.style.display = 'none';
                // Reset for next open
                gsap.set(lightboxContent, { scale: 0.8, opacity: 0 });
            }
        });
    } else {
        lightbox.style.opacity = '0';
        lightboxContent.style.transform = 'scale(0.9)';
        lightboxContent.style.opacity = '0';
        setTimeout(() => {
            lightbox.style.display = 'none';
            lightboxContent.style.transform = 'scale(0.8)';
        }, 250);
    }

    // Restore body scroll
    document.body.style.overflow = '';
}

